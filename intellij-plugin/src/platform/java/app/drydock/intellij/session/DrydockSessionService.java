    private static final int MAX_TRANSFER_OUTPUT = 256 * 1024;
    private static final String TRANSFER_BEGIN = "DRYDOCK_TRANSFER_V1_BEGIN_";
    private static final String TRANSFER_END = "DRYDOCK_TRANSFER_V1_END_";

